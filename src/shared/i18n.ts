export type Locale = 'en' | 'de';

const MESSAGES: Readonly<Record<Locale, Readonly<Record<MessageKey, string>>>> = { en, de };

/** Looks up a message and fills `{name}` parameters. Unknown parameters stay visible. */
export function translate(
  locale: Locale,
  key: MessageKey,
  params: Readonly<Record<string, string | number>> = {},
): string {
  return MESSAGES[locale][key].replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = params[name];
    return value === undefined ? whole : String(value);
  });
}

/** Resolves the `system` language from an OS locale such as `de-AT`. */
export function resolveLocale(preference: 'system' | Locale, systemLocale: string): Locale {
  if (preference !== 'system') return preference;
  return systemLocale.toLowerCase().startsWith('de') ? 'de' : 'en';
}

/** Every message key, for completeness tests. */
export function messageKeys(): readonly MessageKey[] {
  return Object.keys(en) as MessageKey[];
}
